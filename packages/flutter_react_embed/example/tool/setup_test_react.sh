#!/usr/bin/env bash
#
# setup_test_react.sh
#
# Builds a pinned open-source React SPA and installs its production output as
# the example app's embedded bundle (example/assets/react_app/).
#
# Steps:
#   1. Preflight: git, node (>= 20), npm, perl.
#   2. Fetch REPO_URL at REPO_REF (tag, branch or commit) into SRC_DIR.
#   3. npm install, then npm run build.
#   4. Locate the build output (build/ or dist/) and check every local
#      <script>/<link> in index.html resolves to a file in it.
#   5. Replace example/assets/react_app/ with the output (source maps dropped
#      unless KEEP_SOURCEMAPS=1).
#   6. Install tool/fre-bridge.js and load it first in index.html.
#   7. Rewrite the generated asset block in example/pubspec.yaml (Flutter does
#      not include subdirectories of an asset directory, so every directory is
#      listed).
#   8. Write lib/react_app_manifest.g.dart with the index.html SHA-256, which
#      the app passes as bundleSha256 so the native host verifies the bundle.
#
# Usage:
#   tool/setup_test_react.sh            build and install
#   tool/setup_test_react.sh --clean    remove the installed bundle and restore
#                                       the placeholder pubspec block/manifest
#
# Environment overrides:
#   REPO_URL          git URL of the React app
#   REPO_REF          tag, branch or commit to build (pin it for reproducibility)
#   SRC_DIR           checkout directory (default: example/.react_src)
#   KEEP_SOURCEMAPS   1 to keep *.map files (default: 0)
#   NPM_INSTALL_ARGS  extra arguments for npm install

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXAMPLE_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

REPO_URL="${REPO_URL:-https://github.com/coreui/coreui-free-react-admin-template.git}"
REPO_REF="${REPO_REF:-v5.7.0}"
SRC_DIR="${SRC_DIR:-$EXAMPLE_DIR/.react_src}"
KEEP_SOURCEMAPS="${KEEP_SOURCEMAPS:-0}"
NPM_INSTALL_ARGS="${NPM_INSTALL_ARGS:-}"

ASSET_REL="assets/react_app"
DEST_DIR="$EXAMPLE_DIR/$ASSET_REL"
PUBSPEC="$EXAMPLE_DIR/pubspec.yaml"
MANIFEST="$EXAMPLE_DIR/lib/react_app_manifest.g.dart"
BRIDGE_SRC="$SCRIPT_DIR/fre-bridge.js"
BEGIN_MARKER="# >>> react_app assets"
END_MARKER="# <<< react_app assets"
MIN_NODE_MAJOR=20

# ------------------------------------------------------------------------------
# Helpers
# ------------------------------------------------------------------------------

step() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
die() {
  printf '\033[1;31merror:\033[0m %s\n' "$*" >&2
  exit 1
}

require() {
  command -v "$1" >/dev/null 2>&1 || die "'$1' is required but not on PATH"
}

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  else
    shasum -a 256 "$1" | cut -d' ' -f1
  fi
}

# Refuse to delete anything that is not exactly example/assets/react_app.
safe_reset_dest() {
  case "$DEST_DIR" in
    */example/assets/react_app) ;;
    *) die "refusing to delete unexpected path: $DEST_DIR" ;;
  esac
  rm -rf "$DEST_DIR"
  mkdir -p "$DEST_DIR"
  touch "$DEST_DIR/.gitkeep"
}

# Replaces the lines between the pubspec markers with "- <dir>/" entries.
write_pubspec_assets() {
  local entries_file="$1"
  grep -qF "$BEGIN_MARKER" "$PUBSPEC" || die "marker '$BEGIN_MARKER' not found in $PUBSPEC"
  grep -qF "$END_MARKER" "$PUBSPEC" || die "marker '$END_MARKER' not found in $PUBSPEC"
  local tmp
  tmp="$(mktemp)"
  awk -v begin="$BEGIN_MARKER" -v end="$END_MARKER" -v entries="$entries_file" '
    index($0, begin) {
      print
      indent = substr($0, 1, index($0, "#") - 1)
      while ((getline line < entries) > 0) print indent "- " line
      close(entries)
      skipping = 1
      next
    }
    index($0, end) { skipping = 0 }
    !skipping { print }
  ' "$PUBSPEC" >"$tmp"
  mv "$tmp" "$PUBSPEC"
}

write_manifest() {
  local available="$1" sha="$2" commit="$3" files="$4" built_at="$5"
  cat >"$MANIFEST" <<EOF
// GENERATED by tool/setup_test_react.sh. Do not edit by hand.
part of 'react_app_manifest.dart';

const ReactAppManifest reactAppManifest = ReactAppManifest(
  available: $available,
  bundle: '$ASSET_REL/',
  indexSha256: $sha,
  repository: '$REPO_URL',
  ref: '$REPO_REF',
  commit: $commit,
  fileCount: $files,
  builtAt: $built_at,
);
EOF
}

clean() {
  step "Removing the installed bundle"
  safe_reset_dest
  local entries
  entries="$(mktemp)"
  printf '%s/\n' "$ASSET_REL" >"$entries"
  write_pubspec_assets "$entries"
  rm -f "$entries"
  write_manifest false null null 0 null
  info "Restored placeholder pubspec asset block and $(basename "$MANIFEST")"
}

if [[ "${1:-}" == "--clean" ]]; then
  clean
  exit 0
fi
[[ $# -eq 0 ]] || die "unknown argument: $1 (use --clean or no arguments)"

# ------------------------------------------------------------------------------
# 1. Preflight
# ------------------------------------------------------------------------------

step "Checking tools"
for tool in git node npm perl awk; do require "$tool"; done
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
((NODE_MAJOR >= MIN_NODE_MAJOR)) || die "Node $MIN_NODE_MAJOR+ required, found $(node --version)"
[[ -f "$BRIDGE_SRC" ]] || die "missing $BRIDGE_SRC"
info "node $(node --version), npm $(npm --version), $(git --version)"

# ------------------------------------------------------------------------------
# 2. Fetch the pinned revision
# ------------------------------------------------------------------------------

step "Fetching $REPO_URL @ $REPO_REF"
if [[ ! -d "$SRC_DIR/.git" ]]; then
  git init --quiet "$SRC_DIR"
  git -C "$SRC_DIR" remote add origin "$REPO_URL"
else
  git -C "$SRC_DIR" remote set-url origin "$REPO_URL"
fi
# Works for tags, branches and full commit SHAs, and keeps the clone shallow.
git -C "$SRC_DIR" fetch --quiet --depth 1 origin "$REPO_REF"
git -C "$SRC_DIR" -c advice.detachedHead=false checkout --quiet --force FETCH_HEAD
# Drop stale build output but keep node_modules as an install cache.
git -C "$SRC_DIR" clean --quiet -fdx -e node_modules
COMMIT="$(git -C "$SRC_DIR" rev-parse HEAD)"
info "checked out $COMMIT"

# ------------------------------------------------------------------------------
# 3. Install and build
# ------------------------------------------------------------------------------

step "npm install"
# shellcheck disable=SC2086 # NPM_INSTALL_ARGS is intentionally word-split.
(cd "$SRC_DIR" && npm install --no-audit --no-fund $NPM_INSTALL_ARGS)

step "npm run build"
(cd "$SRC_DIR" && npm run build)

# ------------------------------------------------------------------------------
# 4. Locate and validate the output
# ------------------------------------------------------------------------------

step "Validating build output"
OUT_DIR=""
for candidate in build dist; do
  if [[ -f "$SRC_DIR/$candidate/index.html" ]]; then
    OUT_DIR="$SRC_DIR/$candidate"
    break
  fi
done
[[ -n "$OUT_DIR" ]] || die "no build/index.html or dist/index.html after npm run build"
find "$OUT_DIR" -name '*.js' -print -quit | grep -q . || die "no JavaScript files in $OUT_DIR"

# The host serves the bundle at its origin root, so every local reference must
# resolve inside the output. A failure here usually means the app was built
# for a sub-path (Vite `base`, CRA `homepage`).
missing=0
while IFS= read -r ref; do
  case "$ref" in
    http:* | https:* | //* | data:* | \#*) continue ;;
  esac
  path="${ref%%[?#]*}"
  path="${path#./}"
  path="${path#/}"
  if [[ -n "$path" && ! -e "$OUT_DIR/$path" ]]; then
    warn "index.html references '$ref', which is not in the build output"
    missing=1
  fi
done < <(grep -oE '(src|href)="[^"]+"' "$OUT_DIR/index.html" | sed -E 's/^(src|href)="//; s/"$//')
((missing == 0)) || die "index.html references files outside the bundle; build with base '/' or './'"
info "output: ${OUT_DIR#"$SRC_DIR"/}/ ($(find "$OUT_DIR" -type f | wc -l | tr -d ' ') files)"

# ------------------------------------------------------------------------------
# 5. Install into example/assets/react_app
# ------------------------------------------------------------------------------

step "Installing into $ASSET_REL/"
safe_reset_dest
cp -R "$OUT_DIR/." "$DEST_DIR/"
if [[ "$KEEP_SOURCEMAPS" != "1" ]]; then
  find "$DEST_DIR" -type f -name '*.map' -delete
fi

# ------------------------------------------------------------------------------
# 6. Bridge shim
# ------------------------------------------------------------------------------

step "Injecting the flutter_react_embed bridge shim"
cp "$BRIDGE_SRC" "$DEST_DIR/fre-bridge.js"
# A classic, non-deferred script at the top of <head> runs before the app's
# module scripts, so the bridge exists before React starts.
perl -0pi -e 's/(<head\b[^>]*>)/$1\n    <script src=".\/fre-bridge.js"><\/script>/i' "$DEST_DIR/index.html"
grep -q 'fre-bridge.js' "$DEST_DIR/index.html" || die "could not find <head> in index.html to inject the bridge"

# ------------------------------------------------------------------------------
# 7. pubspec asset block
# ------------------------------------------------------------------------------

step "Updating $(basename "$PUBSPEC") asset list"
ENTRIES="$(mktemp)"
trap 'rm -f "$ENTRIES"' EXIT
(cd "$EXAMPLE_DIR" && find "$ASSET_REL" -type f ! -name '.gitkeep' -exec dirname {} \; | sort -u | sed 's|$|/|') >"$ENTRIES"
write_pubspec_assets "$ENTRIES"
sed 's/^/    - /' "$ENTRIES"

# ------------------------------------------------------------------------------
# 8. Manifest for integrity pinning
# ------------------------------------------------------------------------------

step "Writing $(basename "$MANIFEST")"
INDEX_SHA="$(sha256_of "$DEST_DIR/index.html")"
FILE_COUNT="$(find "$DEST_DIR" -type f ! -name '.gitkeep' | wc -l | tr -d ' ')"
BUILT_AT="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
write_manifest true "'$INDEX_SHA'" "'$COMMIT'" "$FILE_COUNT" "'$BUILT_AT'"
info "index.html sha256 $INDEX_SHA"

step "Done"
info "Bundle: $ASSET_REL/ ($FILE_COUNT files, $(du -sh "$DEST_DIR" | cut -f1))"
info "Run the app:   cd $EXAMPLE_DIR && flutter run"
info "Run the tests: cd $EXAMPLE_DIR && flutter test integration_test -d <device-id>"
